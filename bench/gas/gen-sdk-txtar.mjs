// generates a gno.land integration testscript that measures the gas of one AnchorCheckpoint as
// the SDK realm's anchor history grows. Embeds the SDK packages from the given tree (tests excluded), registers one
// agent, subscribes it to the Pro plan (one-block anchor cadence), then anchors N chained checkpoints, one transaction
// each (prevRoot = the previous root, leafCount rising). Every anchor's GAS USED lands in the log; the script ends on
// a deliberate non-match so testscript prints it. Usage: node gen-sdk-txtar.mjs <sdk repo> <anchors> <label> <out>
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const [sdk, nArg, label, out] = process.argv.slice(2);
const n = Number(nArg);
if (!sdk || !Number.isInteger(n) || n < 1 || !label || !out) throw new Error('usage: gen-sdk-txtar.mjs <sdk repo> <anchors> <label> <out>');
const pkgs = [
  ['gno.land/p/arobi/signals', 'gno.land/p/arobi/signals', 'signals'],
  ['gno.land/p/arobi/assurance', 'gno.land/p/arobi/assurance', 'passurance'],
  ['gno.land/r/arobi/assurance', 'gno.land/r/arobi/assurance', 'rassurance'],
];
// Five agents in turn: the in-memory node can put two transactions in one block, and an agent's anchors must be at
// least a block apart (the Pro cadence). The global anchor tree and accumulator still grow with every anchor.
const AGENTS = 5;
const root = (i) => (i <= 0 ? '0'.repeat(64) : createHash('sha256').update(`arobi-gas-checkpoint-${i}`).digest('hex'));
const call = (func, args, send) =>
  `gnokey maketx call -pkgpath gno.land/r/arobi/assurance -func ${func}${args.map((a) => ` -args '${a}'`).join('')}` +
  `${send ? ` -send ${send}` : ''} -gas-fee 90000001ugnot -gas-wanted 900000000 -chainid=tendermint_test test1\nstdout 'OK!'\n`;

let s = `# SDK AnchorCheckpoint gas as anchor history grows (${label}): ${n} anchors, one transaction each. Generated by gen-sdk-txtar.mjs.\n\n`;
s += 'loadpkg gno.land/p/nt/avl/v0\n';
for (const [p, , dir] of pkgs) s += `loadpkg ${p} $WORK/${dir}\n`;
s += '\ngnoland start\n\n';
for (let a = 0; a < AGENTS; a++) {
  s += call('RegisterAgent', [`gas-agent-${a}`, `Gas Agent ${a}`, '1'.repeat(64), '']);
  s += call('SubscribeAgent', [`gas-agent-${a}`], '10000000ugnot');
}
for (let i = 1; i <= n; i++) {
  const a = (i - 1) % AGENTS, k = Math.floor((i - 1) / AGENTS) + 1; // agent a's k-th anchor
  const rk = (j) => (j <= 0 ? root(0) : root((j - 1) * AGENTS + a + 1));
  s += `# send ${i}\n` + call('AnchorCheckpoint', [`gas-agent-${a}`, rk(k), rk(k - 1), String(k), String(k), String(k)], '1000ugnot');
}
s += "\n# The end: a deliberate non-match, so testscript prints the whole log (every GAS USED) for gas-curve.mjs.\nstdout 'GAS_HARNESS_DUMP_SENTINEL'\n\n";
for (const [, rel, name] of pkgs) {
  const dir = path.join(sdk, rel);
  for (const f of fs.readdirSync(dir).sort()) {
    if (!(f.endsWith('.gno') || f === 'gnomod.toml') || f.endsWith('_test.gno') || f.endsWith('_filetest.gno')) continue;
    s += `-- ${name}/${f} --\n${fs.readFileSync(path.join(dir, f), 'utf8').replace(/\r\n/g, '\n')}\n`;
  }
}
fs.writeFileSync(out, s);
console.log(`${out}: ${n} anchors, ${(s.length / 1024).toFixed(0)} KB`);
